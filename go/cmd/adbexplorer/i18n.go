func (a *app) tr(key string) string {
	pair, ok := phrases[key]
	if !ok {
		return key
	}
	if a.lang == "en" {
		return pair[0]
	}
	return pair[1]
}

func (a *app) trf(key string, args ...any) string {
	return fmt.Sprintf(a.tr(key), args...)
}
