// native returns the native-only message for key in locale, "" when the
// locale has none.
func native(locale, key string) string {
	if messages, ok := nativeMessages[locale]; ok {
		if v, ok := messages[key]; ok {
			return v
		}
	}
	if v, ok := nativeMessages["en"][key]; ok {
		return v
	}
	return ""
}
